"""Read-only discovery of documentary candidates from DefiLlama protocol metadata.

Input: output/holder_value_discovery.csv (generated by the existing engine).
Output: output/holder_value_auto_sources.csv, output/holder_value_auto_summary.json.

A fetched homepage is NEVER proof of token-holder economic capture. This module
never modifies investment datasets, scoring, verification flags or quality gates.
Only exact identity matches and explicitly published HTTPS candidate URLs are
considered. Network calls are bounded and redirects are not followed.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlparse

import pandas as pd
import requests

MAX_CANDIDATES = 30
MAX_BYTES = 250_000
TIMEOUT = (5, 12)
FIELDS = [
    "coin_id", "symbol", "name", "protocol_name", "protocol_slug",
    "discovery_status", "candidate_url", "candidate_url_kind",
    "source_catalogue", "fetch_status", "http_status", "content_type",
    "content_sha256", "retrieved_at_utc", "excerpt", "evidence_scope",
    "economic_mechanism_verified", "audit_note",
]


def _valid_url(url: str) -> bool:
    """Conservative public HTTPS URL check; no arbitrary URLs accepted."""
    try:
        p = urlparse(url)
        if p.scheme != "https" or not p.hostname or p.username or p.password:
            return False
        if p.port not in (None, 443):
            return False
        host = p.hostname.lower().rstrip(".")
        if host == "localhost" or host.endswith(".local"):
            return False
        # IP literal hosts are rejected. Hostname DNS safety is checked by the
        # existing curated collector; this module restricts to catalogue URLs.
        import ipaddress
        try:
            ipaddress.ip_address(host)
            return False
        except ValueError:
            return bool(re.fullmatch(r"[a-z0-9.-]+", host)) and "." in host
    except (ValueError, AttributeError):
        return False


def _fetch(url: str, session: requests.Session) -> dict:
    """Bounded metadata retrieval, no redirects, no interpretation as proof."""
    try:
        with session.get(
            url, timeout=TIMEOUT, stream=True, allow_redirects=False,
            headers={"Accept": "text/html,text/plain,application/json"},
        ) as response:
            status = response.status_code
            mime = response.headers.get("Content-Type", "").split(";")[0].lower()
            if status != 200:
                return {"fetch_status": "HTTP_NOT_OK", "http_status": status,
                        "audit_note": "Non-200 response or redirect; no evidence verified"}
            if mime not in {"text/html", "text/plain", "application/json"}:
                return {"fetch_status": "UNSUPPORTED_CONTENT", "http_status": status,
                        "content_type": mime, "audit_note": "Unsupported document type"}
            chunks, size = [], 0
            for chunk in response.iter_content(chunk_size=32768):
                size += len(chunk)
                if size > MAX_BYTES:
                    return {"fetch_status": "TOO_LARGE", "http_status": status,
                            "audit_note": "Document exceeded bounded download"}
                chunks.append(chunk)
            content = b"".join(chunks)
            excerpt = re.sub(r"\s+", " ", content.decode("utf-8", "replace"))[:400]
            return {
                "fetch_status": "HOMEPAGE_RETRIEVED_UNVERIFIED",
                "http_status": status, "content_type": mime,
                "content_sha256": hashlib.sha256(content).hexdigest(),
                "retrieved_at_utc": datetime.now(timezone.utc).isoformat(),
                "excerpt": excerpt,
                "audit_note": "Homepage retrieved; no economic mechanism, token attribution or period verified",
            }
    except requests.RequestException as exc:
        return {"fetch_status": "NETWORK_ERROR", "audit_note": type(exc).__name__}


def collect(discovery: pd.DataFrame, max_candidates: int = MAX_CANDIDATES,
            session: requests.Session | None = None) -> pd.DataFrame:
    """Select unique exact matches only; keep results research-only."""
    required = {"coin_id", "symbol", "name", "discovery_status", "candidate_url"}
    missing = required - set(discovery.columns)
    if missing:
        raise ValueError("Discovery CSV missing: " + ", ".join(sorted(missing)))
    if not 1 <= max_candidates <= MAX_CANDIDATES:
        raise ValueError(f"max_candidates must be 1..{MAX_CANDIDATES}")
    selected = discovery.loc[
        discovery["discovery_status"].fillna("").astype(str).eq("CANDIDATE_FOUND_UNVERIFIED")
    ].copy()
    selected = selected.drop_duplicates(subset=["coin_id"], keep=False)
    selected = selected.sort_values("coin_id", kind="stable").head(max_candidates)
    own_session = session is None
    session = session or requests.Session()
    rows = []
    try:
        for _, item in selected.iterrows():
            row = {field: "" for field in FIELDS}
            for field in ("coin_id", "symbol", "name", "protocol_name", "protocol_slug",
                          "discovery_status", "candidate_url", "candidate_url_kind"):
                if field in selected.columns and pd.notna(item[field]):
                    row[field] = str(item[field]).strip()
            row.update({
                "source_catalogue": "https://api.llama.fi/protocols",
                "evidence_scope": "PROTOCOL_HOMEPAGE_CANDIDATE_ONLY",
                "economic_mechanism_verified": False,
            })
            if not row["coin_id"] or not _valid_url(row["candidate_url"]):
                row.update(fetch_status="INVALID_CANDIDATE", audit_note="Missing coin_id or invalid HTTPS URL")
            else:
                row.update(_fetch(row["candidate_url"], session))
            rows.append(row)
    finally:
        if own_session:
            session.close()
    return pd.DataFrame(rows, columns=FIELDS)


def main() -> None:
    parser = argparse.ArgumentParser(description="Read-only automatic Holder Value source discovery")
    parser.add_argument("--discovery", default="output/holder_value_discovery.csv")
    parser.add_argument("--output", default="output/holder_value_auto_sources.csv")
    parser.add_argument("--max-candidates", type=int, default=MAX_CANDIDATES)
    args = parser.parse_args()
    source = Path(args.discovery)
    if not source.is_file():
        parser.error(f"Discovery report not found: {source}")
    discovery = pd.read_csv(source, dtype=str, keep_default_na=False)
    results = collect(discovery, max_candidates=args.max_candidates)
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    results.to_csv(output, index=False, encoding="utf-8-sig")
    summary = {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "input": str(source), "input_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "candidates_checked": len(results),
        "homepages_retrieved": int((results["fetch_status"] == "HOMEPAGE_RETRIEVED_UNVERIFIED").sum()),
        "economic_mechanisms_verified": 0,
        "approval_flags_modified": False,
        "warning": "Homepage retrieval does not prove economic capture, buybacks, burns, distributions or real yield",
    }
    output.with_name("holder_value_auto_summary.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(summary, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
